export function initBottomNavEvents() {
  const items = document.querySelectorAll('.bottom-nav-item[href]');
  items.forEach(item => {
    item.addEventListener('click', () => {
      items.forEach(i => i.classList.remove('active'));
      item.classList.add('active');
    });
  });

  const lodgeBtn = document.getElementById('btn-bottom-lodge');
  if (lodgeBtn) {
    lodgeBtn.addEventListener('click', () => {
      const modalTrigger = document.getElementById('btn-open-complaint-modal');
      if (modalTrigger) modalTrigger.click();
    });
  }
}
